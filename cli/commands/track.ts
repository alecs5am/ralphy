import { existsSync, readFileSync, writeFileSync, mkdirSync } from "node:fs";
import path from "node:path";
import { out } from "../lib/output.js";
import { raiseError } from "../lib/errors/index.js";
import {
  faceModelPath,
  runTracker,
  setupTrackEngine,
  trackEngineStatus,
  TrackEngineError,
  TRACK_STACK,
} from "../lib/track/engine.js";
import {
  computeTrackStats,
  DEFAULT_TRACK_METHOD,
  parseBox,
  parseQuad,
  parseTrackTime,
  TRACK_METHODS,
  TRACK_SCHEMA_ID,
  TrackDocumentSchema,
  type TrackDocument,
  type TrackKind,
} from "../lib/track/schema.js";
import runtimeSource from "../lib/track/ralphy-track.js" with { type: "text" };

/** `a.json` -> `a.json` if free, else `a.v2.json`, `a.v3.json`, ... */
export function nextFreeFile(target: string, exists: (p: string) => boolean = existsSync): string {
  if (!exists(target)) return target;
  const ext = path.extname(target);
  const stem = target.slice(0, target.length - ext.length);
  for (let v = 2; v < 10_000; v++) {
    const cand = `${stem}.v${v}${ext}`;
    if (!exists(cand)) return cand;
  }
  throw new Error(`too many versions of ${target}`);
}

export function defaultTrackOut(video: string, kind: TrackKind): string {
  const dir = path.dirname(path.resolve(video));
  const stem = path.basename(video, path.extname(video));
  return path.join(dir, `${stem}.track-${kind}.json`);
}

type TrackOpts = {
  at: string;
  to?: string;
  box?: string;
  quad?: string;
  method?: string;
  out?: string;
  procWidth?: string;
  minConfidence?: string;
  js?: boolean;
};

/**
 * A classic-script loader for a track: HyperFrames builds timelines
 * synchronously at load, so the composition reads the track from a global
 * instead of fetching JSON. Registers under the output file's stem.
 */
export function trackLoaderScript(name: string, doc: unknown): string {
  return (
    `// Generated by \`ralphy track\`. Registers window.__tracks[${JSON.stringify(name)}].\n` +
    `(window.__tracks = window.__tracks || {})[${JSON.stringify(name)}] = ${JSON.stringify(doc)};\n`
  );
}

function engineFail(e: unknown): never {
  if (e instanceof TrackEngineError) {
    if (e.kind === "missing") raiseError("E_DEP_MISSING", { dep: `local tracking engine (${e.message})` });
    if (e.kind === "input") raiseError("E_INPUT_INVALID", { field: "track", detail: e.message, verb: "track" });
    if (e.kind === "dependency") raiseError("E_DEP_MISSING", { dep: `${e.message} (re-run \`ralphy track setup --force\`)` });
    raiseError("E_INTERNAL", { detail: e.message });
  }
  raiseError("E_INTERNAL", { detail: e instanceof Error ? e.message : String(e) });
}

async function runTrack(kind: TrackKind, video: string, opts: TrackOpts): Promise<void> {
  const verb = `track ${kind}`;
  const videoPath = path.resolve(video);
  if (!existsSync(videoPath)) raiseError("E_FILE_UNREADABLE", { path: videoPath });
  const at = parseTrackTime(opts.at);
  if (!Number.isFinite(at)) raiseError("E_INPUT_INVALID", { field: "--at", detail: `not a time: ${opts.at}`, verb });
  let to: number | null = null;
  if (opts.to !== undefined) {
    to = parseTrackTime(opts.to);
    if (!Number.isFinite(to) || to <= at) raiseError("E_INPUT_INVALID", { field: "--to", detail: "must be a time later than --at", verb });
  }
  const method = opts.method ?? DEFAULT_TRACK_METHOD[kind];
  if (!TRACK_METHODS[kind].includes(method)) {
    raiseError("E_FLAG_UNKNOWN", { flag: "method", value: method, allowed: TRACK_METHODS[kind].join(", "), verb });
  }
  const box = opts.box ? parseBox(opts.box) : null;
  if (opts.box && !box) raiseError("E_INPUT_INVALID", { field: "--box", detail: "expected x,y,w,h with w,h > 0 (source pixels)", verb });
  const quad = opts.quad ? parseQuad(opts.quad) : null;
  if (opts.quad && !quad) raiseError("E_INPUT_INVALID", { field: "--quad", detail: "expected x1,y1,x2,y2,x3,y3,x4,y4 (TL, TR, BR, BL)", verb });
  if (kind === "point" && !box) raiseError("E_FLAG_MISSING", { flag: "box", verb });
  if (kind === "planar" && !box && !quad) raiseError("E_FLAG_MISSING", { flag: "box (or --quad)", verb });
  const procWidth = opts.procWidth !== undefined ? Number(opts.procWidth) : 960;
  if (!Number.isInteger(procWidth) || procWidth < 0) raiseError("E_INPUT_INVALID", { field: "--proc-width", detail: "expected an integer >= 0 (0 = native)", verb });
  const minConfidence = opts.minConfidence !== undefined ? Number(opts.minConfidence) : 0.3;
  if (!(minConfidence >= 0 && minConfidence <= 1)) raiseError("E_INPUT_INVALID", { field: "--min-confidence", detail: "expected 0..1", verb });

  const args = ["--mode", kind, "--method", method, "--video", videoPath, "--at", String(at), "--proc-width", String(procWidth), "--min-confidence", String(minConfidence)];
  if (to !== null) args.push("--to", String(to));
  if (box) args.push("--box", box.join(","));
  if (quad) args.push("--quad", quad.flat().join(","));
  if (kind === "face") {
    if (method === "mediapipe" && !existsSync(faceModelPath())) {
      raiseError("E_DEP_MISSING", { dep: "face model (run `ralphy track setup`)" });
    }
    if (method === "yunet") {
      const yunet = process.env.RALPHY_TRACK_YUNET_MODEL;
      if (!yunet || !existsSync(yunet)) {
        raiseError("E_DEP_MISSING", { dep: "YuNet model (set RALPHY_TRACK_YUNET_MODEL to a face_detection_yunet .onnx file)" });
      }
      args.push("--face-model", yunet);
    } else {
      args.push("--face-model", faceModelPath());
    }
  }

  let engine;
  try {
    engine = await runTracker(args);
  } catch (e) {
    engineFail(e);
  }

  const keyframes = engine.keyframes as TrackDocument["keyframes"];
  const status = trackEngineStatus();
  const doc: TrackDocument = {
    schema: TRACK_SCHEMA_ID,
    kind,
    method: engine.method,
    createdAt: new Date().toISOString(),
    source: { path: videoPath, ...engine.source },
    seed: { at, to, box, quad },
    engine: {
      name: "opencv-local",
      stack: status.stack,
      python: engine.engine.python,
      opencv: engine.engine.opencv,
      numpy: engine.engine.numpy,
      mediapipe: engine.engine.mediapipe ?? null,
      providerCalls: 0,
    },
    stats: computeTrackStats(keyframes),
    keyframes,
  };
  const parsed = TrackDocumentSchema.safeParse(doc);
  if (!parsed.success) {
    raiseError("E_INTERNAL", { detail: `tracker output failed schema: ${parsed.error.issues.slice(0, 3).map((i) => `${i.path.join(".")}: ${i.message}`).join("; ")}` });
  }

  const requested = opts.out ? path.resolve(opts.out) : defaultTrackOut(videoPath, kind);
  const target = nextFreeFile(requested);
  mkdirSync(path.dirname(target), { recursive: true });
  writeFileSync(target, JSON.stringify(doc, null, 2) + "\n", { flag: "wx" });
  let loader: string | null = null;
  let loaderName: string | null = null;
  if (opts.js) {
    loaderName = path.basename(target, ".json");
    loader = nextFreeFile(target.replace(/\.json$/, "") + ".js");
    writeFileSync(loader, trackLoaderScript(loaderName, doc), { flag: "wx" });
  }

  out({
    kind,
    method: doc.method,
    out: target,
    versioned: target !== requested,
    loader,
    loaderName,
    video: videoPath,
    at,
    to,
    keyframes: doc.stats.keyframes,
    tracked: doc.stats.tracked,
    lost: doc.stats.lost,
    meanConfidence: doc.stats.meanConfidence,
    firstLostAt: doc.stats.firstLostAt,
    providerCalls: 0,
  });
}

function addTrackOptions(cmd: Command, kind: TrackKind): Command {
  cmd
    .argument("<video>", "Source video (any format ffmpeg/OpenCV can decode)")
    .requiredOption("--at <t>", "Seed time: seconds, MM:SS, or HH:MM:SS. Tracking runs forward from here")
    .option("--to <t>", "Stop time (default: end of video)")
    .option("--method <m>", `Tracker: ${TRACK_METHODS[kind].join(" | ")} (default ${DEFAULT_TRACK_METHOD[kind]})`)
    .option("--out <json>", "Output path (default: <video-dir>/<stem>.track-<kind>.json; never overwritten, next free .vN is used)")
    .option("--proc-width <px>", "Downscale frames to this width for tracking; output stays in source pixels (default 960, 0 = native)")
    .option("--min-confidence <0..1>", "Keyframes below this confidence are flagged lost (default 0.3)")
    .option("--js", "Also write a <stem>.js loader that registers the track as window.__tracks[<stem>] for HyperFrames", false);
  if (kind === "planar") {
    cmd
      .option("--box <x,y,w,h>", "Axis-aligned seed region in source pixels (becomes the corner-pin quad)")
      .option("--quad <x1,y1,..,x4,y4>", "Seed quad TL, TR, BR, BL in source pixels (overrides --box)");
  } else if (kind === "point") {
    cmd.option("--box <x,y,w,h>", "Seed region around the feature, source pixels (required)");
  } else {
    cmd.option("--box <x,y,w,h>", "Pick the face nearest this box (default: the largest face at --at)");
  }
  return cmd;
}

export function trackCmd(): Command {
  const cmd = new Command("track").description(
    "Local motion tracking with zero provider calls: point, planar (corner pin), and face tracks as JSON keyframes for HyperFrames.",
  );

  cmd
    .command("setup")
    .description(`Install the pinned local tracking engine (${TRACK_STACK.id}) with uv; idempotent`)
    .option("--force", "Reinstall packages and re-download the face model", false)
    .action(async (opts: { force?: boolean }) => {
      const res = await setupTrackEngine({
        force: opts.force,
        log: (s) => process.stderr.write(`track setup: ${s}\n`),
      });
      out({
        installed: res.status.installed,
        stack: res.status.stack,
        dir: res.status.dir,
        python: res.status.python,
        faceModel: res.status.faceModel,
        steps: res.steps,
      });
      if (!res.status.installed) process.exitCode = 1;
    });

  addTrackOptions(cmd.command("point").description("Track a point (feature region) forward from --at; keyframes carry x, y, box"), "point").action(
    (video: string, opts: TrackOpts) => runTrack("point", video, opts),
  );
  addTrackOptions(cmd.command("planar").description("Track a planar region (screen, sign, label) as a corner pin; keyframes carry four corners"), "planar").action(
    (video: string, opts: TrackOpts) => runTrack("planar", video, opts),
  );
  addTrackOptions(cmd.command("face").description("Track one face box forward from --at with a local detector"), "face").action(
    (video: string, opts: TrackOpts) => runTrack("face", video, opts),
  );

  cmd
    .command("helper")
    .description("Write the HyperFrames runtime (ralphy-track.js: follow + cornerPin) next to a composition")
    .option("--out <path>", "Destination file (default ./ralphy-track.js); an existing different file is kept and the next free .vN is used")
    .action((opts: { out?: string }) => {
      const requested = path.resolve(opts.out ?? "ralphy-track.js");
      let target = requested;
      let unchanged = false;
      if (existsSync(requested)) {
        if (readFileSync(requested, "utf8") === runtimeSource) unchanged = true;
        else target = nextFreeFile(requested);
      }
      if (!unchanged) {
        mkdirSync(path.dirname(target), { recursive: true });
        writeFileSync(target, runtimeSource, { flag: "wx" });
      }
      out({
        out: target,
        unchanged,
        versioned: target !== requested,
        usage: "<script src=\"ralphy-track.js\"></script> then RalphyTrack.follow(tl, el, track, opts) or RalphyTrack.cornerPin(tl, el, track, opts)",
      });
    });

  return cmd;
}
