// `ralphy track` — local, provider-free motion tracking (issue #559).
//
//   ralphy track setup [--force]
//   ralphy track point  <video> --at <t> --box x,y,w,h [--to <t>] [--method klt|csrt|kcf] [--out <json>]
//   ralphy track planar <video> --at <t> (--box x,y,w,h | --quad x1,y1,..,x4,y4) [--method hybrid|klt|sift]
//   ralphy track face   <video> --at <t> [--box x,y,w,h] [--method mediapipe|yunet]
//   ralphy track helper [--out <path>]
//
// Every track verb writes one `ralphy.track/v1` JSON document (keyframes of
// time -> point / corner pin / face box, each with a confidence and a lost
// flag). Outputs are append-only: an existing file is never overwritten; the
// next free `<stem>.v2.json`, `<stem>.v3.json`, ... is used instead.
//
// Free before paid: nothing here calls a model provider. The engine runs
// OpenCV / MediaPipe locally from the pinned venv `ralphy track setup` makes.

