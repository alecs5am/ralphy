// Font-pair specimen compositions (#565). One 1080x1920 HyperFrames page per
// pair: the English specimen first, then the Russian one, so a single preview
// shows whether both faces hold up in Latin and Cyrillic. Rendered by
// `ralphy catalog fonts preview` into .ralphy/catalog/previews/fonts/<id>.mp4.

import { fontFaceCss, type FontFaceSpec } from "./harness.js";
import { FONT_PAIR_SAMPLE, type SampleLang } from "./samples.js";
import type { FontManifest, FontPair } from "./fonts.js";

/** Display sizes that fit the 880 px column; wide or pixel faces need less. */
const DISPLAY_SIZE: Record<string, number> = {
  "press-start-2p": 58,
  unbounded: 90,
  "rubik-wet-paint": 104,
  caveat: 150,
  "jetbrains-mono": 92,
  "cormorant-garamond": 112,
};

function esc(s: string): string {
  return s.replace(/&/g, "&amp;").replace(/</g, "&lt;").replace(/>/g, "&gt;");
}

export const FONT_PAIR_SEGMENT = 2.4;

export function buildFontPairHtml(pair: FontPair, manifest: FontManifest, faces: FontFaceSpec[]): string {
  const font = (id: string) => manifest.fonts.find((f) => f.id === id)!;
  const d = font(pair.display.font);
  const b = font(pair.body.font);
  const size = DISPLAY_SIZE[d.id] ?? 112;
  const total = FONT_PAIR_SEGMENT * 2;
  const block = (lang: SampleLang, i: number) => {
    const s = FONT_PAIR_SAMPLE[lang];
    return `
      <div class="fp-block clip" id="fp-${lang}" data-start="${i * FONT_PAIR_SEGMENT}" data-duration="${FONT_PAIR_SEGMENT}" data-track-index="1">
        <div class="fp-lang">${lang === "en" ? "English" : "Russian"} / ${esc(pair.register)}</div>
        <div class="fp-display">${esc(s.headline)}</div>
        <div class="fp-body">${esc(s.body)}</div>
        <div class="fp-pangram">${esc(s.pangram)}</div>
      </div>`;
  };
  const credit = `${d.family} ${pair.display.weight} + ${b.family} ${pair.body.weight}`;
  const licenses = [...new Set([d.license.id, b.license.id])].join(", ");
  return `<!doctype html>
<!-- Generated by \`ralphy catalog fonts preview\` from catalog/fonts.json pair ${pair.id} (#565). Do not hand-edit. -->
<html lang="en">
  <head>
    <meta charset="UTF-8" />
    <script src="https://cdn.jsdelivr.net/npm/gsap@3.14.2/dist/gsap.min.js"></script>
    <style>
${fontFaceCss(faces)}
html, body { margin: 0; width: 1080px; height: 1920px; overflow: hidden; background: ${pair.colors.background}; }
#root { position: absolute; inset: 0; background: ${pair.colors.background}; color: ${pair.colors.ink}; }
.fp-block { position: absolute; left: 100px; top: 280px; width: 880px; }
.fp-lang { font-family: "${b.family}", sans-serif; font-weight: 600; font-size: 30px; letter-spacing: 4px; text-transform: uppercase; color: ${pair.colors.accent}; }
.fp-display { margin-top: 40px; font-family: "${d.family}", sans-serif; font-weight: ${pair.display.weight}; font-size: ${size}px; line-height: 1.05; text-transform: ${pair.display.transform}; letter-spacing: ${pair.display.tracking}em; }
.fp-body { margin-top: 56px; font-family: "${b.family}", sans-serif; font-weight: ${pair.body.weight}; font-size: 50px; line-height: 1.3; }
.fp-pangram { margin-top: 48px; font-family: "${b.family}", sans-serif; font-weight: ${pair.body.weight}; font-size: 36px; line-height: 1.35; opacity: 0.7; }
.fp-credit { position: absolute; left: 100px; top: 1330px; width: 880px; font-family: "${b.family}", sans-serif; font-weight: 500; font-size: 28px; line-height: 1.4; opacity: 0.75; }
.fp-rule { position: absolute; left: 100px; top: 1300px; width: 880px; height: 4px; background: ${pair.colors.accent}; transform-origin: 0% 50%; }
    </style>
  </head>
  <body>
    <div id="root" data-composition-id="main" data-width="1080" data-height="1920" data-start="0" data-duration="${total}">
${block("en", 0)}
${block("ru", 1)}
      <div class="fp-rule" id="fp-rule"></div>
      <div class="fp-credit">${esc(credit)}<br />${esc(licenses)} / free for commercial video</div>
    </div>
    <script>
  window.__timelines = window.__timelines || {};
  var tl = gsap.timeline({ paused: true });
  ["en", "ru"].forEach(function (lang, i) {
    var t = i * ${FONT_PAIR_SEGMENT};
    tl.from("#fp-" + lang + " .fp-display", { y: 50, opacity: 0, duration: 0.5, ease: "power3.out" }, t + 0.1);
    tl.from("#fp-" + lang + " .fp-body", { y: 30, opacity: 0, duration: 0.45, ease: "power3.out" }, t + 0.3);
    tl.from("#fp-" + lang + " .fp-pangram", { opacity: 0, duration: 0.4, ease: "power2.out" }, t + 0.45);
  });
  tl.from("#fp-rule", { scaleX: 0, duration: 0.6, ease: "expo.out" }, 0.2);
  window.__timelines["main"] = tl;
    </script>
  </body>
</html>
`;
}
