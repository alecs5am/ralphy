function esc(s) { return String(s).replace(/[&<>"]/g, function (c) { return { "&": "&amp;", "<": "&lt;", ">": "&gt;", '"': "&quot;" }[c]; }); }
function matches(it) {
  if (state.kind.size && !state.kind.has(it.kind)) return false;
  if (state.energy.size && !state.energy.has(it.energy)) return false;
  if (state.mood.size && !it.moods.some(function (m) { return state.mood.has(m); })) return false;
  if (state.q) {
    var hay = [it.id, it.name, it.summary, it.whenToUse, it.tags.join(" "), it.moods.join(" ")].join(" ").toLowerCase();
    if (hay.indexOf(state.q) < 0) return false;
  }
  return true;
}
